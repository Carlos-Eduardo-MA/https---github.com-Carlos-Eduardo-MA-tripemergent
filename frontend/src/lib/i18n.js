export const LANGS = [
  { code: "pt", label: "PT", locale: "pt-BR" },
  { code: "en", label: "EN", locale: "en-US" },
  { code: "es", label: "ES", locale: "es-ES" },
];

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("tg_lang") || (navigator.language || "pt").slice(0, 2).replace(/[^a-z]/g, "") || "pt");
  const safe = DICT[lang] ? lang : "pt";
  useEffect(() => {
    localStorage.setItem("tg_lang", safe);
    document.documentElement.lang = safe;
  }, [safe]);
  const t = useCallback((k) => DICT[safe][k] ?? DICT.pt[k] ?? k, [safe]);
  const locale = LANGS.find((l) => l.code === safe).locale;
  return <I18nContext.Provider value={{ lang: safe, setLang, t, locale }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
